    // ── coalescing must not demote the trigger ───────────────────────────────────────────────────

    /// <summary>
    /// The trigger a coalesced deploy runs under is the <em>strongest</em> of the requests that merged
    /// into it. An operator's Deploy landing on a pending fan-out must run the full pipeline: without
    /// this the button would report success having done nothing, on a stack that is on the newest
    /// release but whose compose file or environment just changed.
    /// </summary>
    [Fact]
    public async Task Enqueue_CoalescingAManualDeployOntoAPendingRelease_RunsTheFullPipeline() {
        var run = await RunCoalescedAsync(
            firstTrigger: DeployTriggers.Release,
            pendingTrigger: DeployTriggers.Release,
            coalescedTrigger: DeployTriggers.Manual);

        Assert.Equal("success", run.Status);
        Assert.DoesNotContain("nothing to do", run.Output, StringComparison.Ordinal);
        // Two deploys reached compose: the one that was running, and the coalesced pending one.
        Assert.Equal(2, run.UpCount);
    }

    /// <summary>
    /// The reverse never demotes either: a fan-out coalescing onto a pending manual keeps "manual",
    /// because a full deploy is never the wrong answer to a release arriving.
    /// </summary>
    [Fact]
    public async Task Enqueue_CoalescingAReleaseOntoAPendingManualDeploy_StillRunsTheFullPipeline() {
        var run = await RunCoalescedAsync(
            firstTrigger: DeployTriggers.Manual,
            pendingTrigger: DeployTriggers.Manual,
            coalescedTrigger: DeployTriggers.Release);

        Assert.Equal("success", run.Status);
        Assert.DoesNotContain("nothing to do", run.Output, StringComparison.Ordinal);
        Assert.Equal(2, run.UpCount);
    }

    /// <summary>
    /// …and a pure fan-out pile-up still short-circuits, which is the behaviour the promotion rule must
