/// <summary>
/// The behaviour-changing half of ADR-0026: what a deploy does once a product is in
/// <see cref="ProductReleaseMode.Releases"/>, and — the acceptance test for the whole stage — what it
/// still does when the product is in <see cref="ProductReleaseMode.Git"/>.
/// </summary>
/// <remarks>
/// Both out-of-process steps are doubles that <em>record</em>: <see cref="StubGitCloneService"/> which
/// clone form was asked for, <see cref="RecordingComposeCliService"/> the whole compose argument list
/// and the override file's content while it existed. That is what lets invariant 1 — "a product with no
/// releases deploys byte-for-byte as it did before" — be an assertion about the calls rather than a
/// claim about the code.
/// </remarks>
public sealed class ReleaseDeployTests {
    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    private const string SingleService = """
        { "services": { "api": { "image": "ghcr.io/acme/api:latest" } } }
        """;

    private const string ApiAndDb = """
        {
          "services": {
            "api": { "image": "ghcr.io/acme/api:latest" },
            "db": { "image": "postgres:16" }
          }
        }
        """;

    // ── invariant 1: Git mode is untouched ───────────────────────────────────────────────────────

    /// <summary>
    /// The golden record. A product in <c>Git</c> mode clones the branch head, writes an override with
    /// no <c>image:</c> in it, stamps no release on the event and leaves the stack's release columns
    /// null — which together <em>are</em> "deploys as it did before ADR-0026".
    /// </summary>
    /// <remarks>
    /// Deliberately asserted as exact values rather than as absences: "there is no image line" would
    /// still pass if the whole override had stopped being written.
    /// </remarks>
    [Fact]
    public async Task Deploy_OfAGitModeProduct_ClonesTheBranchHeadAndPinsNothing() {
        using var host = AuthTestHost.Start();
        var productId = await host.AddProductAsync("shop", ProductReleaseMode.Git);
        var stackId = await host.AddProductStackAsync("shop-prod", productId);
        // Releases may exist and still change nothing: the mode is the switch, not their presence.
        await host.AddReleaseAsync(productId, "v1");

        var run = await RunDeployAsync(host, stackId, ApiAndDb);

        Assert.Equal("success", run.Status);
        Assert.Equal(
            [new GitInvocation("clone", "https://example.invalid/shop.git", "main")],
            run.Clones);
        Assert.Equal(
            $"""
            # Generated by Watchtower for this deploy — not part of the repository.
            services:
              'api':
                environment:
                  'WATCHTOWER_STACK_ID': '{stackId}'
              'db':
                environment:
                  'WATCHTOWER_STACK_ID': '{stackId}'

            """.ReplaceLineEndings("\n"),
            run.Compose.Invocation("up").OverrideContent);
        Assert.DoesNotContain("Deploying release", run.Output, StringComparison.Ordinal);
        Assert.DoesNotContain("Pinning service", run.Output, StringComparison.Ordinal);
        Assert.Null(await EventReleaseAsync(host, run.EventId));
        Assert.Equal((null, null), await host.ReleaseStateAsync(stackId));
    }

    /// <summary>
    /// The mutation of the test above: the <em>only</em> thing changed is the product's mode, and every
    /// assertion that held for Git mode now fails to hold. Without this, the golden test could be
    /// passing because the release machinery never runs at all.
    /// </summary>
    [Fact]
    public async Task Deploy_OfAReleaseModeProduct_ClonesTheCommitAndPinsTheDigest() {
        using var host = AuthTestHost.Start();
        var productId = await host.AddProductAsync("shop");
        var stackId = await host.AddProductStackAsync("shop-prod", productId);
        var releaseId = await host.AddReleaseAsync(productId, "v1");

        var run = await RunDeployAsync(host, stackId, ApiAndDb);

        Assert.Equal("success", run.Status);
        Assert.Equal(
            [new GitInvocation(
                "clone-at-commit", "https://example.invalid/shop.git", "main", ReleaseTestEstate.ReleaseCommit)],
            run.Clones);
        // 'db' runs postgres, which the release did not build — untouched, and no allowlist said so.
        Assert.Equal(
            $"""
            # Generated by Watchtower for this deploy — not part of the repository.
            services:
              'api':
                image: 'ghcr.io/acme/api@{ReleaseTestEstate.ApiDigest}'
                environment:
                  'WATCHTOWER_STACK_ID': '{stackId}'
              'db':
                environment:
                  'WATCHTOWER_STACK_ID': '{stackId}'

            """.ReplaceLineEndings("\n"),
            run.Compose.Invocation("up").OverrideContent);
        Assert.Contains(
            $"[Watchtower] Deploying release v1 (commit {ReleaseTestEstate.ReleaseCommit[..8]})",
            run.Output, StringComparison.Ordinal);
        Assert.Contains(
            $"[Watchtower] Pinning service 'api' to ghcr.io/acme/api@{ReleaseTestEstate.ApiDigest}",
            run.Output, StringComparison.Ordinal);
        Assert.Equal(releaseId, await EventReleaseAsync(host, run.EventId));
        Assert.Equal((null, releaseId), await host.ReleaseStateAsync(stackId));
    }

