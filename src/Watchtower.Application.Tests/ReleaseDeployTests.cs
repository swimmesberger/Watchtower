    /// <summary>
    /// Convergence (invariant 3): the deploy resolves its release when it <em>runs</em>, so a release
    /// published after the enqueue is the one that gets deployed — not the one that was newest when the
    /// work was queued.
    /// </summary>
    /// <remarks>
    /// Staged through the cross-stack gate, which is the real mechanism a fan-out drains behind: one
    /// stack holds the only permit while a second deploy — enqueued when v1 was newest — waits, and v2
    /// lands during the wait. Had the release id been captured at enqueue, the waiting deploy would
    /// still run v1; the assertion is that it runs v2.
    /// </remarks>
    [Fact]
    public async Task Deploy_ResolvesTheReleaseThatLandedWhileItWaitedAtTheGate() {
        using var host = AuthTestHost.Start(("Watchtower:MaxConcurrentDeploys", "1"));
        var productId = await host.AddProductAsync("shop");
        await host.AddReleaseAsync(productId, "v1");
        var holderId = await host.AddProductStackAsync("holder", productId);
        var waitingId = await host.AddProductStackAsync("waiting", productId);

        var probe = new ConcurrencyProbeComposeCliService { Hold = TimeSpan.FromMilliseconds(500) };
        var git = new StubGitCloneService();
        using var gateQueue = CreateQueue(host, probe, git);
        var holderEvent = await CreateDeployEventAsync(host, holderId, DeployTriggers.Release);
        var waitingEvent = await CreateDeployEventAsync(host, waitingId, DeployTriggers.Release);

        var holder = Task.Run(
            () => gateQueue.ExecuteDeployAsync(holderId, holderEvent, DeployTriggers.Release, null, Ct), Ct);
        await WaitUntilAsync(async () => await StatusOfAsync(host, holderEvent) == "running");
        var waiting = Task.Run(
            () => gateQueue.ExecuteDeployAsync(waitingId, waitingEvent, DeployTriggers.Release, null, Ct), Ct);
        await WaitUntilAsync(async () =>
            (await OutputOfAsync(host, waitingEvent)).Contains("Waiting for a deploy slot", StringComparison.Ordinal));

        // v2 is published while the second deploy is parked — exactly the "release lands mid-drain" case.
        var v2 = await host.AddReleaseAsync(
            productId, "v2", ReleaseTestEstate.NextReleaseCommit,
            ("ghcr.io/acme/api", ReleaseTestEstate.NextApiDigest));

        await Task.WhenAll(holder, waiting);

        Assert.Equal("success", await StatusOfAsync(host, waitingEvent));
        Assert.Equal(v2, await EventReleaseAsync(host, waitingEvent));
        Assert.Equal(v2, (await host.ReleaseStateAsync(waitingId)).LastDeployed);
        Assert.Contains(
            new GitInvocation(
                "clone-at-commit", "https://example.invalid/shop.git", "main",
                ReleaseTestEstate.NextReleaseCommit),
            git.Clones);
    }

    /// <summary>
    /// The same staleness rule the stopped-stack re-check follows: a pin written while the deploy sat at
    /// the gate is honoured, because the release is resolved from the stack read on the far side of it.
    /// </summary>
    [Fact]
    public async Task Deploy_HonoursAPinWrittenWhileItWaitedAtTheGate() {
        using var host = AuthTestHost.Start(("Watchtower:MaxConcurrentDeploys", "1"));
        var productId = await host.AddProductAsync("shop");
        var v1 = await host.AddReleaseAsync(productId, "v1");
        await host.AddReleaseAsync(
            productId, "v2", ReleaseTestEstate.NextReleaseCommit,
            ("ghcr.io/acme/api", ReleaseTestEstate.NextApiDigest));
        var holderId = await host.AddProductStackAsync("holder", productId);
        var waitingId = await host.AddProductStackAsync("waiting", productId);

        var probe = new ConcurrencyProbeComposeCliService { Hold = TimeSpan.FromMilliseconds(500) };
        var git = new StubGitCloneService();
        using var gateQueue = CreateQueue(host, probe, git);
        var holderEvent = await CreateDeployEventAsync(host, holderId, DeployTriggers.Manual);
        var waitingEvent = await CreateDeployEventAsync(host, waitingId, DeployTriggers.Manual);

        var holder = Task.Run(
            () => gateQueue.ExecuteDeployAsync(holderId, holderEvent, DeployTriggers.Manual, null, Ct), Ct);
        await WaitUntilAsync(async () => await StatusOfAsync(host, holderEvent) == "running");
        var waiting = Task.Run(
            () => gateQueue.ExecuteDeployAsync(waitingId, waitingEvent, DeployTriggers.Manual, null, Ct), Ct);
        await WaitUntilAsync(async () =>
            (await OutputOfAsync(host, waitingEvent)).Contains("Waiting for a deploy slot", StringComparison.Ordinal));

        // The operator pins the parked stack back to v1 while it waits.
        await host.PinAsync(waitingId, v1);
        await Task.WhenAll(holder, waiting);

        Assert.Equal(v1, await EventReleaseAsync(host, waitingEvent));
    }

