    // ── resolution ───────────────────────────────────────────────────────────────────────────────

    /// <summary>A pin outranks "newest": the whole point of pinning is that later releases do not move it.</summary>
    [Fact]
    public async Task Deploy_OfAPinnedStack_DeploysThePinRatherThanTheNewestRelease() {
        using var host = AuthTestHost.Start();
        var productId = await host.AddProductAsync("shop");
        var oldId = await host.AddReleaseAsync(productId, "v1");
        await host.AddReleaseAsync(
            productId, "v2", ReleaseTestEstate.NextReleaseCommit,
            ("ghcr.io/acme/api", ReleaseTestEstate.NextApiDigest));
