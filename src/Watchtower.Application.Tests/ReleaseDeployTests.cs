    /// </summary>
    [Fact]
    public async Task Deploy_ThatShortCircuits_LeavesTheStacksLastDeployFieldsAlone() {
        using var host = AuthTestHost.Start();
        var productId = await host.AddProductAsync("shop");
        var releaseId = await host.AddReleaseAsync(productId, "v1");
        var stackId = await host.AddProductStackAsync("shop-prod", productId);
        await host.SetDeployedReleaseAsync(stackId, releaseId);
        var deployedAt = new DateTimeOffset(2026, 8, 1, 9, 0, 0, TimeSpan.Zero);
        await SetLastDeployAsync(host, stackId, deployedAt, DeployStatus.Success);

