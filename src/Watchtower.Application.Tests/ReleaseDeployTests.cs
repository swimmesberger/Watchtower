    // ── Helpers ──────────────────────────────────────────────────────────────────────────────────

    /// <summary>What one deploy left behind, plus the two recorders it ran against.</summary>
    private sealed record DeployRun(
        int EventId, string Status, string Output,
        IReadOnlyList<GitInvocation> Clones, RecordingComposeCliService Compose);

    /// <summary>Runs one deploy to completion on the calling thread, as <see cref="DeployEnvInjectionTests"/> does.</summary>
    private static async Task<DeployRun> RunDeployAsync(
        AuthTestHost host, int stackId, string configJson,
        string trigger = DeployTriggers.Manual, IReadOnlyList<string>? removeVolumes = null,
        int upExitCode = 0) {
        var compose = new RecordingComposeCliService { ConfigJson = configJson, UpExitCode = upExitCode };
        var git = new StubGitCloneService();
        var eventId = await CreateDeployEventAsync(host, stackId, trigger);

        using (var queue = CreateQueue(host, compose, git))
            await queue.ExecuteDeployAsync(stackId, eventId, trigger, removeVolumes, Ct);

        await using var scope = host.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<WatchtowerDbContext>();
        var deployEvent = await db.DeployEvents.AsNoTracking().FirstAsync(e => e.Id == eventId, Ct);
        return new DeployRun(
            eventId, deployEvent.Status, deployEvent.Output ?? string.Empty, git.Clones, compose);
    }

    /// <summary>What the coalesced pending deploy did.</summary>
    /// <param name="UpCount">How many deploys reached <c>compose up</c> — the short-circuit's tell.</param>
    private sealed record CoalescedRun(string Status, string Output, int UpCount);

    /// <summary>
    /// Drives the three-request coalescing path through the real <see cref="DeployQueueService.Enqueue"/>:
    /// one deploy running, one pending, and a third that merges onto the pending slot.
    /// </summary>
    /// <remarks>
    /// The first deploy is held inside its <c>config</c> call, which is what makes the sequence
    /// deterministic rather than a race: <c>Enqueue</c> flips <c>IsRunning</c> synchronously under the
    /// slot lock, so with the worker parked the second call is guaranteed to become the pending slot and
    /// the third to coalesce onto it. The stack starts on no release and the first deploy puts it on the
    /// newest one, so by the time the pending deploy runs it <em>is</em> converged — which is exactly the
    /// state where the trigger decides between a full deploy and a no-op.
    /// </remarks>
    private static async Task<CoalescedRun> RunCoalescedAsync(
        string firstTrigger, string pendingTrigger, string coalescedTrigger) {
        using var host = AuthTestHost.Start();
        var productId = await host.AddProductAsync("shop");
        await host.AddReleaseAsync(productId, "v1");
        var stackId = await host.AddProductStackAsync("shop-prod", productId);

        var held = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var compose = new RecordingComposeCliService {
            ConfigJson = SingleService,
            OnConfig = () => held.Task,
        };
        using var queue = CreateQueue(host, compose, new StubGitCloneService());

        var first = queue.Enqueue(stackId, firstTrigger);
        Assert.Equal("running", first.Status);
        var pending = queue.Enqueue(stackId, pendingTrigger);
        Assert.Equal("queued", pending.Status);
        var coalesced = queue.Enqueue(stackId, coalescedTrigger);
        // The third request produced no new row — it merged onto the pending one.
        Assert.Equal(pending.DeployEventId, coalesced.DeployEventId);

        // Let the first deploy finish; the worker then picks the pending slot up with the merged trigger.
        // Only the first deploy is gated: the hook is cleared before the second one reaches config.
        compose.OnConfig = null;
        held.SetResult();
        await WaitUntilAsync(async () => await StatusOfAsync(host, pending.DeployEventId) is "success" or "failed");
        await queue.StopAsync(Ct);

        return new CoalescedRun(
            await StatusOfAsync(host, pending.DeployEventId),
            await OutputOfAsync(host, pending.DeployEventId),
            compose.Invocations.Count(i => i.Command == "up"));
    }

    private static DeployQueueService CreateQueue(
        AuthTestHost host, ComposeCliService compose, GitCloneService git) =>
        new(host.Services.GetRequiredService<IServiceScopeFactory>(),
            git,
            compose,
