    private static async Task<int> CreateDeployEventAsync(AuthTestHost host, int stackId, string trigger) {
        await using var scope = host.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<WatchtowerDbContext>();
        var deployEvent = new DeployEvent {
            StackId = stackId, TriggeredBy = trigger, Status = "queued", StartedAt = DateTimeOffset.UtcNow,
        };
        db.DeployEvents.Add(deployEvent);
        await db.SaveChangesAsync(Ct);
        return deployEvent.Id;
    }

    private static async Task<int?> EventReleaseAsync(AuthTestHost host, int eventId) {
        await using var scope = host.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<WatchtowerDbContext>();
        return await db.DeployEvents.AsNoTracking()
            .Where(e => e.Id == eventId).Select(e => e.ReleaseId).FirstAsync(Ct);
    }

    /// <summary>Backdates the stack's last-deploy fields, so "untouched" is checkable.</summary>
    private static async Task SetLastDeployAsync(
        AuthTestHost host, int stackId, DateTimeOffset at, DeployStatus status) {
        await using var scope = host.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<WatchtowerDbContext>();
        await db.Stacks.Where(s => s.Id == stackId)
            .ExecuteUpdateAsync(
                s => s.SetProperty(x => x.LastDeployedAt, at).SetProperty(x => x.LastDeployStatus, status),
                Ct);
    }

    private static async Task<(DateTimeOffset? At, DeployStatus? Status)> LastDeployAsync(
        AuthTestHost host, int stackId) {
        await using var scope = host.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<WatchtowerDbContext>();
        var row = await db.Stacks.AsNoTracking()
            .Where(s => s.Id == stackId)
            .Select(s => new { s.LastDeployedAt, s.LastDeployStatus })
            .FirstAsync(Ct);
        return (row.LastDeployedAt, row.LastDeployStatus);
    }

    private static async Task<string> StatusOfAsync(AuthTestHost host, int eventId) {
